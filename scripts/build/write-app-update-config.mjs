#!/usr/bin/env node
/**
 * 给 ad-hoc 发布链的 mac 产物补 electron-updater 运行时配置(app-update.yml)。
 *
 * 背景:`package:mac:adhoc` 是 `--dir` 构建 + `--prepackaged` 打 dmg/zip,这条链不会生成
 * Contents/Resources/app-update.yml —— electron-updater 在下载阶段要读它(updaterCacheDirName),
 * 缺失时下载直接 ENOENT 失败(2026-09 端到端实测)。正常 `package:mac`(签名链)由
 * electron-builder 自动生成,不走本脚本。
 *
 * url 写 stable 默认 feed;运行时 UpdaterService.setFeedURL 按通道设置覆盖 url,
 * 这里只保证文件存在与缓存目录名稳定。
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_FEED_URL = 'https://zhaozhaoyue.top/Musefold/updates/stable/';
const DEFAULT_UPDATER_CACHE_DIR_NAME = 'musefold-app-updater';

export function buildAppUpdateYaml({
  url = DEFAULT_FEED_URL,
  updaterCacheDirName = DEFAULT_UPDATER_CACHE_DIR_NAME,
} = {}) {
  return [
    '## Generated by scripts/build/write-app-update-config.mjs (ad-hoc release chain).',
    `provider: generic`,
    `url: ${url}`,
    `updaterCacheDirName: ${updaterCacheDirName}`,
    '',
  ].join('\n');
}

export function appUpdateYmlPath(appPath) {
  return join(appPath, 'Contents', 'Resources', 'app-update.yml');
}

async function main() {
  const appPath = process.argv[2];
  if (!appPath) {
    console.error('usage: node scripts/build/write-app-update-config.mjs <Musefold.app path>');
    process.exit(1);
  }
  const urlArgIndex = process.argv.indexOf('--url');
  const url = urlArgIndex > -1 ? process.argv[urlArgIndex + 1] : DEFAULT_FEED_URL;
  const target = resolve(appPath);
  if (!target.endsWith('.app')) {
    console.error(`refusing to write app-update.yml outside a .app bundle: ${target}`);
    process.exit(1);
  }
  const ymlPath = appUpdateYmlPath(target);
  await mkdir(dirname(ymlPath), { recursive: true });
  await writeFile(ymlPath, buildAppUpdateYaml({ url }), 'utf8');
  console.log(`app-update.yml written: ${ymlPath}`);
}

// import 安全:单测只拿 buildAppUpdateYaml/appUpdateYmlPath,直接 import 不触发写入。
const invokedAsScript =
  process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (invokedAsScript) {
  await main();
}
