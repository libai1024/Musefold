#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { lstat, readdir, readFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const json = args.has('--json');
const help = args.has('--help') || args.has('-h');

if (help) {
  console.log(`Usage: npm run release:status -- [--json]

Checks local release artifacts and prints the external gates that still need
manual evidence. This command does not contact GitHub, sign binaries, install
on Windows ARM64 hardware, or call a real image API.`);
  process.exit(0);
}

const checks = [];
const manualGates = [
  {
    name: 'GitHub Actions remote CI first green run',
    evidence: 'Run npm run release:ci:evidence -- --run-url <Actions run URL>, then record githubActionsRemoteGreen in release/release-gate-evidence.json.',
  },
  {
    name: 'Windows hosted runner x64 installed-app runtime smoke',
    evidence: 'Windows CI logs for tests/package/windows_runtime_smoke.py plus the windows-hosted-runtime-evidence artifact generated by npm run release:windows:hosted.',
  },
  {
    name: 'Windows ARM64 target-device runtime smoke',
    evidence: 'Run npm run release:windows:target on macOS for current hashes, then record target device install/start/generate/media/history/export/import/protocol evidence.',
  },
  {
    name: 'Developer ID signing and macOS notarization',
    evidence: 'Run npm run release:macos:signing -- --emit-evidence on the signing host after codesign/spctl/stapler pass, then record macosDeveloperIdNotarization.',
  },
];

function safePath(path) {
  const absPath = resolve(repoRoot, path);
  const normalized = relative(repoRoot, absPath);
  if (!normalized || normalized.startsWith('..') || isAbsolute(normalized)) {
    throw new Error(`Unsafe path outside repo root: ${path}`);
  }
  return absPath;
}

function record(name, status, details = '') {
  checks.push({ name, status, details });
}

async function exists(path) {
  try {
    await lstat(safePath(path));
    return true;
  } catch (error) {
    if (error && error.code === 'ENOENT') return false;
    throw error;
  }
}

async function statFile(path) {
  const stat = await lstat(safePath(path));
  if (!stat.isFile()) throw new Error(`${path} is not a file`);
  return stat;
}

async function sha256(path) {
  const content = await readFile(safePath(path));
  return createHash('sha256').update(content).digest('hex');
}

function formatBytes(bytes) {
  return `${bytes.toLocaleString('en-US')} bytes`;
}

async function collectMarkdown(baseRel) {
  const baseAbs = safePath(baseRel);
  const files = [];

  async function walk(absDir) {
    let entries;
    try {
      entries = await readdir(absDir, { withFileTypes: true });
    } catch (error) {
      if (error && error.code === 'ENOENT') return;
      throw error;
    }

    for (const entry of entries) {
      const absChild = join(absDir, entry.name);
      if (entry.isDirectory()) {
        await walk(absChild);
      } else if (entry.isFile() && entry.name.endsWith('.md')) {
        files.push(relative(baseAbs, absChild).replaceAll('\\', '/'));
      }
    }
  }

  await walk(baseAbs);
  return files.sort();
}

async function checkArtifacts() {
  const pkg = JSON.parse(await readFile(safePath('package.json'), 'utf8'));
  const version = pkg.version;
  const artifacts = [
    `release/Musefold-${version}-arm64.dmg`,
    `release/Musefold-${version}-arm64-mac.zip`,
    `release/Musefold Setup ${version}.exe`,
    'release/win-arm64-unpacked/Musefold.exe',
  ];

  const summaries = [];
  const missing = [];
  for (const artifact of artifacts) {
    if (!(await exists(artifact))) {
      missing.push(artifact);
      continue;
    }
    const stat = await statFile(artifact);
    summaries.push(`${artifact} (${formatBytes(stat.size)}, sha256 ${await sha256(artifact)})`);
  }

  if (missing.length === 0) {
    record('Release artifacts exist with hashes', 'pass', summaries.join('; '));
  } else {
    record('Release artifacts exist with hashes', 'fail', `missing: ${missing.join(', ')}`);
  }
}

async function checkPackagedDocsSync() {
  const sourceBase = 'docs/product';
  const packageBases = [
    'release/mac-arm64/Musefold.app/Contents/Resources/product-docs',
    'release/win-arm64-unpacked/resources/product-docs',
  ];
  const sourceFiles = await collectMarkdown(sourceBase);
  const issues = [];

  for (const packageBase of packageBases) {
    if (!(await exists(packageBase))) {
      issues.push(`${packageBase}: missing`);
      continue;
    }
    const packagedFiles = await collectMarkdown(packageBase);
    const missing = sourceFiles.filter((file) => !packagedFiles.includes(file));
    const extra = packagedFiles.filter((file) => !sourceFiles.includes(file));
    if (missing.length > 0) issues.push(`${packageBase}: missing ${missing.join(', ')}`);
    if (extra.length > 0) issues.push(`${packageBase}: extra ${extra.join(', ')}`);

    for (const file of sourceFiles) {
      if (missing.includes(file)) continue;
      const source = await readFile(safePath(join(sourceBase, file)), 'utf8');
      const bundled = await readFile(safePath(join(packageBase, file)), 'utf8');
      if (source !== bundled) issues.push(`${packageBase}/${file}: content differs`);
    }
  }

  if (issues.length === 0) {
    record('Packaged product docs match docs/product', 'pass', `${sourceFiles.length} markdown files in macOS and Windows packages`);
  } else {
    record('Packaged product docs match docs/product', 'fail', issues.join('; '));
  }
}

async function checkManifestPreserved() {
  const pkg = JSON.parse(await readFile(safePath('package.json'), 'utf8'));
  const requiredScripts = ['check', 'package:mac', 'package:win', 'release:preflight', 'release:status', 'release:evidence', 'release:ci:evidence', 'release:windows:hosted', 'release:macos:signing', 'release:signing:precheck', 'release:windows:target'];
  const missingScripts = requiredScripts.filter((script) => typeof pkg.scripts?.[script] !== 'string');
  const requiredDevDeps = ['typescript', 'vite', 'vitest', 'electron-builder'];
  const missingDevDeps = requiredDevDeps.filter((dep) => typeof pkg.devDependencies?.[dep] !== 'string');
  if (missingScripts.length === 0 && missingDevDeps.length === 0) {
    record('Development package.json manifest is preserved', 'pass', 'scripts and devDependencies still present after packaging');
  } else {
    record('Development package.json manifest is preserved', 'fail', `missing scripts=${missingScripts.join(', ') || 'none'}; missing devDeps=${missingDevDeps.join(', ') || 'none'}`);
  }
}

async function checkCleanArtifacts() {
  const roots = [
    '.electron-driver',
    '.pytest_cache',
    'test-results',
    'tsconfig.node.tsbuildinfo',
    'tsconfig.web.tsbuildinfo',
  ];
  const hits = [];
  for (const root of roots) {
    if (await exists(root)) hits.push(root);
  }

  for (const base of ['tests/e2e', 'tests/package']) {
    if (!(await exists(base))) continue;
    const stack = [safePath(base)];
    while (stack.length > 0) {
      const dir = stack.pop();
      const entries = await readdir(dir, { withFileTypes: true });
      for (const entry of entries) {
        const absChild = join(dir, entry.name);
        if (entry.isDirectory()) {
          if (entry.name === '__pycache__') hits.push(relative(repoRoot, absChild).replaceAll('\\', '/'));
          else stack.push(absChild);
        }
      }
    }
  }

  if (hits.length === 0) {
    record('Generated test/cache artifacts are clean', 'pass', 'no pytest/driver/tsbuildinfo artifacts found');
  } else {
    record('Generated test/cache artifacts are clean', 'fail', hits.join(', '));
  }
}

async function checkSigningState() {
  const appPath = 'release/mac-arm64/Musefold.app';
  if (!(await exists(appPath))) {
    record('macOS signing/notarization evidence', 'manual', 'app bundle missing locally; rebuild package before signing');
    return;
  }

  const result = spawnSync('codesign', ['--verify', '--deep', '--strict', safePath(appPath)], {
    encoding: 'utf8',
  });
  if (result.status === 0) {
    record('macOS signing/notarization evidence', 'manual', 'codesign verifies locally; still require spctl assessment and notarization ticket evidence');
  } else {
    const details = `${result.stderr || result.stdout || 'codesign failed'}`.trim().split('\n').slice(0, 2).join(' ');
    record('macOS signing/notarization evidence', 'manual', `${details || 'unsigned local development package'}; run npm run release:signing:precheck on the signing host`);
  }
}

async function main() {
  await checkArtifacts();
  await checkPackagedDocsSync();
  await checkManifestPreserved();
  await checkCleanArtifacts();
  await checkSigningState();

  const localFailed = checks.filter((check) => check.status === 'fail');
  const payload = { checks, manualGates, ok: localFailed.length === 0 };

  if (json) {
    console.log(JSON.stringify(payload, null, 2));
  } else {
    console.log('Local release artifact status:');
    for (const check of checks) {
      const mark = check.status === 'pass' ? '✓' : check.status === 'fail' ? '✗' : '○';
      console.log(`${mark} ${check.name}${check.details ? ` — ${check.details}` : ''}`);
    }

    console.log('\nManual gates still needing external evidence:');
    for (const gate of manualGates) {
      console.log(`○ ${gate.name} — ${gate.evidence}`);
    }
    console.log('\nRecord and validate manual evidence with: npm run release:evidence -- --file release/release-gate-evidence.json');
  }

  if (localFailed.length > 0) process.exit(1);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
